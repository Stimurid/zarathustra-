"""HS256 JWT — small, dependency-free, mirror of ``californian_id.jwt_auth``.

The Workbench issues its own tokens rather than reusing the Zarathustra
runtime tokens: the two systems can be deployed with different secrets, and
mixing token audiences would let a runtime API key become a Workbench identity
by accident. Same algorithm, same shape, separate secret.

Secret resolution:
    1. env ``WORKBENCH_JWT_SECRET`` (production);
    2. env ``CALIFORNIAN_ID_JWT_SECRET`` (fallback so a single-secret dev
       setup keeps working);
    3. a stable local secret file at ``<workbench_state>/.jwt_secret`` —
       autogenerated on first use, chmod-narrowed on POSIX. Never used for
       real deployments; the env var must be set there.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import secrets
import time
from pathlib import Path
from typing import Any

ALG = "HS256"
ISS = "tinkuy-workbench"
DEFAULT_TTL_SEC = 24 * 3600

_ENV_PRIMARY = "WORKBENCH_JWT_SECRET"
_ENV_FALLBACK = "CALIFORNIAN_ID_JWT_SECRET"


class TokenError(Exception):
    """Any failure at the JWT boundary — parsing, signature, expiry, issuer."""


def _b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def _b64url_decode(data: str) -> bytes:
    pad = "=" * (-len(data) % 4)
    return base64.urlsafe_b64decode((data + pad).encode("ascii"))


def _secret_bytes(state_dir: Path | None = None) -> bytes:
    for env in (_ENV_PRIMARY, _ENV_FALLBACK):
        val = os.environ.get(env)
        if val:
            return val.encode("utf-8")
    if state_dir is None:
        # Callers that want strict production behaviour set the env var. The
        # local fallback is intentionally quiet, not silent — a warning here
        # would spam every JWT operation.
        return b"workbench-dev-secret-not-for-production"
    secret_path = Path(state_dir) / ".jwt_secret"
    if secret_path.exists():
        return secret_path.read_bytes()
    secret_path.parent.mkdir(parents=True, exist_ok=True)
    secret = secrets.token_bytes(32)
    secret_path.write_bytes(secret)
    try:
        os.chmod(secret_path, 0o600)
    except OSError:
        pass                       # Windows — no unix-mode narrowing available
    return secret


def issue_token(sub: str, roles: list[str], *,
                ttl_sec: int = DEFAULT_TTL_SEC,
                extra_claims: dict[str, Any] | None = None,
                state_dir: Path | None = None) -> tuple[str, int, int]:
    """Return (token, issued_at, expires_at)."""
    now = int(time.time())
    header = {"alg": ALG, "typ": "JWT"}
    payload: dict[str, Any] = {
        "iss": ISS, "sub": sub, "iat": now, "exp": now + int(ttl_sec),
        "roles": list(roles),
    }
    if extra_claims:
        payload.update(extra_claims)
    h = _b64url(json.dumps(header, separators=(",", ":"), ensure_ascii=False).encode("utf-8"))
    p = _b64url(json.dumps(payload, separators=(",", ":"), ensure_ascii=False).encode("utf-8"))
    signing_input = f"{h}.{p}".encode("ascii")
    sig = hmac.new(_secret_bytes(state_dir), signing_input, hashlib.sha256).digest()
    s = _b64url(sig)
    return f"{h}.{p}.{s}", now, now + int(ttl_sec)


def verify_token(token: str, *, state_dir: Path | None = None) -> dict[str, Any]:
    """Return the claims. Raise ``TokenError`` on any invalid input."""
    if not token or token.count(".") != 2:
        raise TokenError("malformed token")
    h_b64, p_b64, s_b64 = token.split(".")
    try:
        header = json.loads(_b64url_decode(h_b64))
        payload = json.loads(_b64url_decode(p_b64))
        sig_actual = _b64url_decode(s_b64)
    except (ValueError, UnicodeDecodeError) as exc:
        raise TokenError(f"undecodable token: {exc}") from None
    if header.get("alg") != ALG:
        raise TokenError(f"unsupported alg: {header.get('alg')!r}")
    signing_input = f"{h_b64}.{p_b64}".encode("ascii")
    sig_expected = hmac.new(_secret_bytes(state_dir), signing_input, hashlib.sha256).digest()
    if not hmac.compare_digest(sig_actual, sig_expected):
        raise TokenError("signature mismatch")
    if payload.get("iss") != ISS:
        raise TokenError(f"unexpected iss: {payload.get('iss')!r}")
    if int(payload.get("exp", 0)) < int(time.time()):
        raise TokenError("token expired")
    return payload


def looks_like_bearer(header_value: str | None) -> str | None:
    """Extract the token from an ``Authorization: Bearer <t>`` header."""
    if not header_value:
        return None
    parts = header_value.strip().split(None, 1)
    if len(parts) != 2 or parts[0].lower() != "bearer":
        return None
    return parts[1].strip() or None
